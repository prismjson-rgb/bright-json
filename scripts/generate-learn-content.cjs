/**
 * Build-time script: reads content/learn/*.md and generates learn-sections.generated.ts
 * Run before build: npm run generate:learn
 */
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const CONTENT_DIR = path.join(process.cwd(), "content", "learn");
const OUT_FILE = path.join(process.cwd(), "src", "lib", "learn-sections.generated.ts");

const LEVELS = [
  { id: "beginner", label: "Basics for Beginners", description: "Never used JSON? Start here." },
  { id: "comfortable", label: "Getting Comfortable", description: "Understand structure and patterns." },
  { id: "practical", label: "Practical JSON", description: "Real-world usage and APIs." },
  { id: "intermediate", label: "Intermediate", description: "Validation, schema, and best practices." },
  { id: "advanced", label: "Advanced", description: "JSON Schema, JSONPath, performance." },
  { id: "expert", label: "Expert Level", description: "Security, streaming, alternatives." },
];

if (!fs.existsSync(CONTENT_DIR)) {
  console.warn("content/learn not found, writing empty sections");
  fs.writeFileSync(
    OUT_FILE,
    `// Auto-generated - run npm run generate:learn to regenerate
export const LEARN_LEVELS = ${JSON.stringify(LEVELS, null, 2)} as const;
export const LEARN_SECTIONS: Array<{
  id: string;
  level: string;
  title: string;
  metaTitle?: string;
  metaDescription?: string;
  contentMarkdown: string;
  excerpt?: string;
  keyTerms: string[];
  tryExample?: string;
}> = [];
`
  );
  process.exit(0);
}

const files = fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".md"));
const sections = [];

for (const file of files) {
  const id = file.replace(/\.md$/, "");
  const raw = fs.readFileSync(path.join(CONTENT_DIR, file), "utf-8");
  const { data, content } = matter(raw);

  const rawContent = content.trim();
  const excerpt =
    data.excerpt ??
    rawContent
      .replace(/^#+ .+$/gm, "")
      .replace(/```[\s\S]*?```/g, "")
      .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
      .replace(/[*_`]/g, "")
      .split(/\n\n/)[0]
      ?.slice(0, 200) ?? "";

  sections.push({
    id,
    level: data.level ?? "beginner",
    title: data.title ?? id.replace(/-/g, " "),
    metaTitle: data.metaTitle,
    metaDescription: data.metaDescription,
    contentMarkdown: rawContent,
    excerpt: (excerpt.trim() || undefined),
    keyTerms: Array.isArray(data.keyTerms) ? data.keyTerms : [],
    tryExample: data.tryExample,
    _order: typeof data.order === "number" ? data.order : 999,
  });
}

sections.sort((a, b) => a._order - b._order);
const out = sections.map(({ _order, ...s }) => s);

const ts = `// Auto-generated by scripts/generate-learn-content.cjs - do not edit
export const LEARN_LEVELS = ${JSON.stringify(LEVELS, null, 2)} as const;

export interface LearnSection {
  id: string;
  level: string;
  title: string;
  metaTitle?: string;
  metaDescription?: string;
  contentMarkdown: string;
  excerpt?: string;
  keyTerms: string[];
  tryExample?: string;
}

export const LEARN_SECTIONS: LearnSection[] = ${JSON.stringify(out, null, 2)};
`;

fs.writeFileSync(OUT_FILE, ts);
console.log(`Generated ${OUT_FILE} with ${out.length} sections`);
process.exit(0);
